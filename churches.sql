-- SQLite script

BEGIN TRANSACTION;

DROP TABLE IF EXISTS states;
DROP TABLE IF EXISTS countries;
DROP TABLE IF EXISTS elders;
DROP TABLE IF EXISTS church_service_attendance;
DROP TABLE IF EXISTS church_services;
DROP TABLE IF EXISTS church_events;
DROP TABLE IF EXISTS churches;

CREATE TABLE countries (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(100) NOT NULL,
    iso_alpha2 VARCHAR(2) NOT NULL,
    iso_alpha3 VARCHAR(3) NOT NULL,
    iso_numeric VARCHAR(3) NOT NULL
);

CREATE TABLE states (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name VARCHAR(150) NOT NULL,

    country_id INT NOT NULL REFERENCES countries(id) ON DELETE CASCADE
);

CREATE TABLE churches (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name VARCHAR(100) NOT NULL,
  address VARCHAR(255) NOT NULL,
  phone VARCHAR(20),
  email VARCHAR(100) NOT NULL,
  description TEXT,
  website VARCHAR(100),
  established DATE,
  facebook VARCHAR(255),
  instagram VARCHAR(255),
  youtube VARCHAR(255),
  spotify VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,

  state_id INT NOT NULL REFERENCES states(id) ON DELETE CASCADE
);

CREATE TABLE elders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL,
  phone VARCHAR(20),
  picture VARCHAR(255), -- URL

  church_id INT NOT NULL REFERENCES churches(id) ON DELETE CASCADE
);

CREATE TABLE church_services (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  church_id INT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
  service_type VARCHAR(100) NOT NULL,
  weekday INTEGER NOT NULL, -- 0 = Sunday, 6 = Saturday
  time TIME NOT NULL
);

CREATE TABLE church_events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  church_id INT NOT NULL REFERENCES churches(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  start_date DATETIME NOT NULL,
  end_date DATETIME,
  location VARCHAR(255), -- NULL MEANS IS AT CHURCH
  image VARCHAR(255), -- URL
  color VARCHAR(50),
  recurrent BOOLEAN DEFAULT FALSE, -- If recurrent, take the start date as the recurrent date
  description TEXT
);

CREATE TABLE church_service_attendance (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  church_service_id INT NOT NULL REFERENCES church_services(id) ON DELETE CASCADE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  visiting_from VARCHAR(100), -- e.g. "Los Angeles, CA"
  attended BOOLEAN
);

